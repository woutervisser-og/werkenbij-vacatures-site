// Geeft kant-en-klare SVG-markup terug om via innerHTML of een
// template-string in de pagina te zetten. "grootte" in pixels, standaard
// 16 (past bij de 14-15px teksten in het portaal).
function icoonSvg(naam, grootte) {
  const pad = ICONEN[naam];
  if (!pad) return "";
  const maat = grootte || 16;
  return `<svg class="icoon" width="${maat}" height="${maat}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${pad}</svg>`;
}
